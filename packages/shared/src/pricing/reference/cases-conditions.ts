/**
 * Reference cases R038–R066: conditions, scopes and exclusions.
 * Most cases use one $20 line and a 10% discount so the only question is
 * whether the rule applies: applied → 1800 + 162 GST = 1962; not applied →
 * 2000 + 180 GST = 2180. Minimum-spend and scope cases use richer baskets.
 */

/** An automatic 10% line-level discount on everything, priority 10; override what differs. */
function disc(id: string, over: Partial<PricingRuleInput> = {}): PricingRuleInput {
  return {
    id,
    kind: "discount",
    name: id,
    calc: "percent",
    value: { type: "fixed", amount: 1000 },
    scope: { type: "all" },
    priority: 10,
    application: "auto",
    report_class: "promo",
    ...over,
  };
}

