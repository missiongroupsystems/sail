import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Writes src/lib/pdf-fonts.generated.ts from the vendored TTFs in assets/fonts (Instrument Sans, SIL OFL 1.1, see
 * assets/fonts/OFL.txt), so the server and its bundle carry the fonts with no file to copy into an image.
 * `tsx scripts/pdf-fonts.ts write` rewrites it; `check` fails when it is out of date (a test runs the same check).
 */
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
export function generatedFontModule(): string {
  const b64 = (f: string) => readFileSync(join(root, "assets/fonts", f)).toString("base64");
  return [
    "// Generated by scripts/pdf-fonts.ts from assets/fonts (Instrument Sans, SIL Open Font License 1.1: assets/fonts/OFL.txt). Do not edit.",
    `export const INSTRUMENT_SANS_REGULAR = "${b64("InstrumentSans-Regular.ttf")}";`,
    `export const INSTRUMENT_SANS_SEMIBOLD = "${b64("InstrumentSans-SemiBold.ttf")}";`,
    "",
  ].join("\n");
}
const target = join(root, "src/lib/pdf-fonts.generated.ts");
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (process.argv[2] === "write") writeFileSync(target, generatedFontModule());
  else if (readFileSync(target, "utf8") !== generatedFontModule()) {
    console.error("src/lib/pdf-fonts.generated.ts is out of date: run tsx scripts/pdf-fonts.ts write");
    process.exit(1);
  }
}
