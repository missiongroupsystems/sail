import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { gunzipSync, gzipSync } from "node:zlib";

/**
 * Builds src/lib/print-font.generated.ts: the GNU Unifont glyphs Sail rasterises receipt and ticket text with when the
 * printer's code page cannot carry it, and the Arabic joining forms taken from the Unicode Character Database.
 *
 *   pnpm exec tsx scripts/print-font.ts <unifont-16.0.04.hex.gz> <UnicodeData.txt>
 *
 * Unifont: https://unifoundry.com/unifont/ (font-builds/unifont-<version>.hex.gz), dual-licensed under the SIL Open
 * Font License 1.1 and GPL-2.0-or-later with the font embedding exception; Sail uses it under the OFL (see
 * src/lib/print-font.LICENSE). UnicodeData.txt: https://www.unicode.org/Public/<version>/ucd/UnicodeData.txt.
 */
const [hexPath, ucdPath] = process.argv.slice(2);
if (!hexPath || !ucdPath) throw new Error("usage: tsx scripts/print-font.ts <unifont.hex.gz> <UnicodeData.txt>");

/** The scripts a receipt may need, beyond what the printer's own code page prints. */
const RANGES: [number, number][] = [
  [0x20, 0x7e], // ASCII, so mixed lines look the same throughout
  [0xa0, 0x24f], // Latin-1 Supplement, Latin Extended-A and -B
  [0x370, 0x3ff], // Greek
  [0x400, 0x4ff], // Cyrillic
  [0x5d0, 0x5ea], // Hebrew letters
  [0x600, 0x6ff], // Arabic
  [0x1e00, 0x1eff], // Latin Extended Additional (Vietnamese)
  [0x2000, 0x206f], // punctuation
  [0x20a0, 0x20cf], // currency signs
  [0x2100, 0x214f],
  [0x2190, 0x21ff],
  [0x2212, 0x2212],
  [0x2460, 0x24ff],
  [0x2500, 0x257f],
  [0x3000, 0x30ff], // CJK punctuation, kana
  [0x3100, 0x33ff], // bopomofo, Hangul compatibility jamo, enclosed CJK
  [0x3400, 0x4dbf], // CJK Extension A
  [0x4e00, 0x9fff], // CJK Unified Ideographs
  [0xac00, 0xd7a3], // Hangul syllables
  [0xf900, 0xfaff],
  [0xfb50, 0xfdff], // Arabic presentation forms A
  [0xfe30, 0xfe4f],
  [0xfe70, 0xfeff], // Arabic presentation forms B
  [0xff00, 0xffef], // halfwidth and fullwidth forms
  [0xfffd, 0xfffd], // replacement character, for anything else
];
const wanted = (cp: number) => RANGES.some(([a, b]) => cp >= a && cp <= b);

const lines = gunzipSync(readFileSync(hexPath)).toString("utf8").split("\n").filter((l) => l && wanted(parseInt(l.slice(0, l.indexOf(":")), 16)));
const glyphs = gzipSync(Buffer.from(lines.join("\n") + "\n"), { level: 9 }).toString("base64");

// Arabic joining forms: presentation-form code points whose decomposition is <isolated|final|initial|medial> of one letter.
const FORM = { isolated: 0, final: 1, initial: 2, medial: 3 } as const;
const forms = new Map<number, [number, number, number, number]>();
const lamAlef = new Map<number, [number, number]>();
for (const row of readFileSync(ucdPath, "utf8").split("\n")) {
  const f = row.split(";");
  const m = /^<(isolated|final|initial|medial)> ([0-9A-F]{4})(?: ([0-9A-F]{4}))?$/.exec(f[5] ?? "");
  if (!m) continue;
  const cp = parseInt(f[0]!, 16);
  if (!((cp >= 0xfb50 && cp <= 0xfdff) || (cp >= 0xfe70 && cp <= 0xfeff))) continue;
  const base = parseInt(m[2]!, 16);
  const form = FORM[m[1] as keyof typeof FORM];
  if (m[3]) {
    // Lam with an alef: one ligature, isolated or final.
    const alef = parseInt(m[3], 16);
    if (base === 0x644 && form <= 1 && [0x622, 0x623, 0x625, 0x627].includes(alef)) {
      const e = lamAlef.get(alef) ?? [0, 0];
      e[form as 0 | 1] = cp;
      lamAlef.set(alef, e);
    }
    continue;
  }
  if (base < 0x600 || base > 0x6ff) continue;
  const e = forms.get(base) ?? [0, 0, 0, 0];
  if (!e[form]) e[form] = cp;
  forms.set(base, e);
}

const out = `// Generated by scripts/print-font.ts from GNU Unifont 16.0.04 and the Unicode Character Database 16.0.0. Do not edit.
// Unifont glyphs are used under the SIL Open Font License 1.1: see print-font.LICENSE next to this file.

/** Unifont .hex lines ("XXXX:bitmap"), gzipped and base64-encoded: ${lines.length} glyphs, 8 or 16 dots wide, 16 tall. */
export const GLYPHS_GZ_BASE64 = "${glyphs}";

/** Arabic letter -> presentation forms [isolated, final, initial, medial]; 0 where the letter has no such form. */
export const ARABIC_FORMS: Record<number, [number, number, number, number]> = ${JSON.stringify(Object.fromEntries([...forms].sort((a, b) => a[0] - b[0])))};

/** Alef variant -> lam-alef ligature [isolated, final]. */
export const LAM_ALEF: Record<number, [number, number]> = ${JSON.stringify(Object.fromEntries([...lamAlef].sort((a, b) => a[0] - b[0])))};
`;
const target = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "lib", "print-font.generated.ts");
writeFileSync(target, out);
console.log(`wrote ${target}: ${lines.length} glyphs, ${forms.size} Arabic letters, ${lamAlef.size} lam-alef ligatures`);
