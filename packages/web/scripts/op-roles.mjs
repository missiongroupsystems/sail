// Writes src/lib/op-roles.ts from the register's OpenAPI manifest: the lowest role each operation allows, so the back
// office can leave out (or explain) what the signed-in role cannot do instead of failing after a form is filled in.
// Run with `node scripts/op-roles.mjs` (part of gen:api); `--check` fails when the file is out of date.
import { readFileSync, writeFileSync } from "node:fs";
const spec = JSON.parse(readFileSync(new URL("../../server/openapi.json", import.meta.url), "utf8"));
const roles = {};
for (const ms of Object.values(spec.paths)) for (const op of Object.values(ms)) if (op["x-sail"]?.min_role) roles[op.operationId] = op["x-sail"].min_role;
const sorted = Object.fromEntries(Object.entries(roles).sort(([a], [b]) => a.localeCompare(b)));
const text = `// Generated by scripts/op-roles.mjs from packages/server/openapi.json. Do not edit.\nimport type { Role } from "@sail/shared";\n\nexport const OP_MIN_ROLE: Record<string, Role> = ${JSON.stringify(sorted, null, 2)};\n`;
const out = new URL("../src/lib/op-roles.ts", import.meta.url);
if (process.argv.includes("--check")) {
  if (readFileSync(out, "utf8") !== text) {
    console.error("src/lib/op-roles.ts is out of date: run node scripts/op-roles.mjs");
    process.exit(1);
  }
} else writeFileSync(out, text);
